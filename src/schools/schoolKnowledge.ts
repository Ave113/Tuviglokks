/** Khối tóm tắt vòng tinh Nam phái cho prompt động */
export function buildDecorativeRingsBlock(palaces: any[]): string {
  if (!Array.isArray(palaces) || palaces.length === 0) return "";
  const lines = palaces.map((p) => {
    const cs = p.changsheng12 || "—";
    const bs = p.boshi12 || "—";
    const jq = p.jiangqian12 || "—";
    const sq = p.suiqian12 || "—";
    const yJ = p.yearJiangqian12 || "—";
    const yS = p.yearSuiqian12 || "—";
    return (
      `  - ${p.name} (${p.earthlyBranch || "?"}): Trường Sinh=${cs} | Bác Sỹ=${bs} | ` +
      `Tướng Tiền(gốc)=${jq} | Tuế Tiền(gốc)=${sq} | ` +
      `Tướng Tiền(năm xem)=${yJ} | Tuế Tiền(năm xem)=${yS}`
    );
  });
  return (
    `--- VÒNG TINH NAM PHÁI (gốc + NĂM XEM) ---\n` +
    `Gốc = bẩm sinh; Năm xem = Tuế Tiền/Tướng Tiền động theo năm hạn (iztro yearlyDecStar). ` +
    `KHÔNG nhầm vòng gốc với vòng năm. Dùng vòng năm khi luận tiểu hạn/lưu niên.\n` +
    lines.join("\n")
  );
}