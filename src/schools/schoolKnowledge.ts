export function buildDualSchoolPromptBlock(): string {
  return `${NAM_TRAN_DOAN_SURFACE_RULES}\n\n${BAC_HA_LAC_INTERNAL_RULES}`;
}

/** Khối tóm tắt vòng tinh Nam phái cho prompt động */
export function buildDecorativeRingsBlock(palaces: any[]): string {
  if (!Array.isArray(palaces) || palaces.length === 0) return "";
  const lines = palaces.map((p) => {
    const cs = p.changsheng12 || "—";
    const bs = p.boshi12 || "—";
    const jq = p.jiangqian12 || "—";
    const sq = p.suiqian12 || "—";
    return `  - ${p.name} (${p.earthlyBranch || "?"}): Trường Sinh=${cs} | Bác Sỹ=${bs} | Tướng Tiền=${jq} | Tuế Tiền=${sq}`;
  });
  return `--- VÒNG TINH NAM PHÁI (4 vòng — đã an sẵn) ---\n${lines.join("\n")}`;
}